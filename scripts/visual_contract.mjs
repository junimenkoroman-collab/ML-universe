/** Minimal dependency-free semantic visualization tests; run with node. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
const root=process.cwd();
const source=fs.readFileSync(path.join(root,'ml_universe/static/visual_story.js'),'utf8');
const window={};
vm.runInNewContext(source,{window,document:{querySelector:()=>null},console});
const {designTraces,plotLayout,lessons}=window.MLStory;
assert.equal(Object.keys(lessons).length,29,'Every curriculum section must have a reading guide');
const classes=designTraces({traces:[{type:'scatter',mode:'markers',x:[1,2,3,4],y:[1,2,3,4],marker:{color:[0,1,0,1]}}]},'light');
assert.equal(classes.length,2,'Categorical classes must be split into discrete legend groups');
assert.deepEqual(Array.from(classes.map(x=>x.name)),['Класс 0','Класс 1']);
assert.notEqual(classes[0].marker.color,classes[1].marker.color);
const initial=designTraces({traces:[{type:'scatter',mode:'lines',x:[0],y:[7],name:'Итоговая ошибка',line:{color:'#148579'}}]},'light');
assert.equal(initial[0].mode,'lines+markers','First training step must be visible as a point');
const segments=designTraces({traces:[{type:'scatter',mode:'lines',name:'Residuals',x:[0,0,null],y:[1,2,null]}]},'light');
assert(segments[0].opacity<0.4,'Dense residual segments should not overpower data');
const heat=designTraces({traces:[{type:'heatmap',z:[[0,.2],[.6,1]],colorscale:'Viridis'}]},'light');
assert(Array.isArray(heat[0].colorscale),'Heatmaps should have a calm sequential color scale');
const layout=plotLayout({title:'Readable',layout:{xaxis:{title:'Feature X'},yaxis:{title:'Prediction'}}},classes,'light',false,{height:400});
assert.equal(layout.title,undefined,'No duplicated heading inside graph');
assert.equal(layout.xaxis.title.text,'Feature X');
assert.equal(layout.yaxis.title.text,'Prediction');
assert.equal(layout.height,400);
const longBar={type:'bar',x:['feature_1 <= 1.25','feature_2 <= 2.50','feature_1 <= 3.25','feature_1 <= 3.50','feature_2 <= 3.75','feature_1 <= 4.25','feature_1 <= 4.50'],y:[1,2,3,4,5,6,7],marker:{color:'#148579'}};
const longLayout=plotLayout({title:'Splits',layout:{yaxis:{title:'Information gain'}}},[longBar],'light',false,{height:350});
assert.equal(longBar.orientation,'h','Long split labels must not collide horizontally');
assert.equal(longLayout.yaxis.autorange,'reversed');
assert(longLayout.height>=350);
const matrixLayout=plotLayout({title:'Attention',layout:{}},[{type:'heatmap',z:[[.4,.6],[.5,.5]]}],'dark',false,{height:330});
assert.equal(matrixLayout.yaxis.scaleanchor,'x','Small square matrix keeps square cells');
const surface=plotLayout({title:'Loss',layout:{scene:{xaxis:{title:'w'},yaxis:{title:'b'},zaxis:{title:'L'}}}},[{type:'surface'}],'light',true,{height:400});
assert(surface.scene&&surface.scene.camera,'3D loss charts retain a legible perspective');
console.log('Visual contract: 29 guides, discrete classes, color scales, axis labels, ranked splits, square attention cells, 3D OK.');
